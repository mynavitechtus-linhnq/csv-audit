export const getDefaultErrorMessage = (
  language: Language,
  ruleType: any,
): string => {
  // Handle both enum and string values
  const typeString =
    typeof ruleType === "string" ? ruleType : String(ruleType).toLowerCase();
  const key = `error.${typeString}`;
  return (
    translations[language][key] ||
    translations[language]["rules.defaultMessage"] ||
    translations.en["rules.defaultMessage"] ||
    key
  );
};

export const t = (language: Language, key: string): string => {
  return translations[language][key] || translations.en[key] || key;
};
